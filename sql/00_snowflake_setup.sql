-- 1. DATABASE & MEDALLION SCHEMAS -------------------------------------------
CREATE DATABASE IF NOT EXISTS LITTLEVITALS_DB;
USE DATABASE LITTLEVITALS_DB;

CREATE SCHEMA IF NOT EXISTS BRONZE;       -- raw ingested data, immutable
CREATE SCHEMA IF NOT EXISTS SILVER;       -- cleaned, typed, deduplicated
CREATE SCHEMA IF NOT EXISTS GOLD;         -- star schema + marts, business-ready
CREATE SCHEMA IF NOT EXISTS SEED;         -- dbt reference seeds
CREATE SCHEMA IF NOT EXISTS RAW;          -- dbt fixture/landing helpers
CREATE SCHEMA IF NOT EXISTS SNAPSHOTS;    -- dbt SCD2 snapshots

-- 2. WAREHOUSE + FINOPS GUARDRAILS (§22) ------------------------------------
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60               -- seconds idle before suspend
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE COMPUTE_WH SET STATEMENT_TIMEOUT_IN_SECONDS = 300;

CREATE RESOURCE MONITOR IF NOT EXISTS LITTLEVITALS_MONITOR
  WITH CREDIT_QUOTA = 50
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 75  PERCENT DO NOTIFY
    ON 90  PERCENT DO SUSPEND
    ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE COMPUTE_WH SET RESOURCE_MONITOR = LITTLEVITALS_MONITOR;

-- 3. RBAC — least privilege, mirrors a real hospital EDW (§3.4) --------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LITTLEVITALS_ENGINEER;   -- all schemas, read/write
CREATE ROLE IF NOT EXISTS LITTLEVITALS_ANALYST;    -- read SILVER + GOLD
CREATE ROLE IF NOT EXISTS LITTLEVITALS_EXECUTIVE;  -- read GOLD only
CREATE ROLE IF NOT EXISTS LITTLEVITALS_READONLY;   -- public-facing GOLD views

-- Warehouse usage
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE LITTLEVITALS_ENGINEER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE LITTLEVITALS_ANALYST;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE LITTLEVITALS_EXECUTIVE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE LITTLEVITALS_READONLY;

-- Database + schema usage
GRANT USAGE ON DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_ENGINEER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_ENGINEER;
GRANT ALL ON ALL SCHEMAS IN DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_ENGINEER;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_ENGINEER;

-- Analyst: read SILVER + GOLD (current + future tables/views)
GRANT USAGE ON DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_ANALYST;
GRANT USAGE ON SCHEMA LITTLEVITALS_DB.SILVER TO ROLE LITTLEVITALS_ANALYST;
GRANT USAGE ON SCHEMA LITTLEVITALS_DB.GOLD   TO ROLE LITTLEVITALS_ANALYST;
GRANT SELECT ON ALL TABLES    IN SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_ANALYST;
GRANT SELECT ON ALL VIEWS     IN SCHEMA LITTLEVITALS_DB.SILVER TO ROLE LITTLEVITALS_ANALYST;

-- Executive + Readonly: GOLD only
GRANT USAGE ON DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_EXECUTIVE;
GRANT USAGE ON SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_EXECUTIVE;
GRANT SELECT ON ALL TABLES    IN SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_EXECUTIVE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_EXECUTIVE;

GRANT USAGE ON DATABASE LITTLEVITALS_DB TO ROLE LITTLEVITALS_READONLY;
GRANT USAGE ON SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_READONLY;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA LITTLEVITALS_DB.GOLD TO ROLE LITTLEVITALS_READONLY;

-- Role hierarchy: engineer inherits everything
GRANT ROLE LITTLEVITALS_ANALYST   TO ROLE LITTLEVITALS_ENGINEER;
GRANT ROLE LITTLEVITALS_EXECUTIVE TO ROLE LITTLEVITALS_ANALYST;
GRANT ROLE LITTLEVITALS_READONLY  TO ROLE LITTLEVITALS_EXECUTIVE;

-- 4. GOVERNANCE: classification tags + masking policy (§23.1) ---------------
USE ROLE ACCOUNTADMIN;
USE SCHEMA LITTLEVITALS_DB.GOLD;

CREATE TAG IF NOT EXISTS data_classification
  ALLOWED_VALUES 'PUBLIC', 'INTERNAL', 'SENSITIVE_SYNTHETIC';

-- Coarsen geography for non-privileged roles (applied to synthetic quasi-IDs).
CREATE MASKING POLICY IF NOT EXISTS mask_postcode AS (val STRING) RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('LITTLEVITALS_ENGINEER', 'LITTLEVITALS_ANALYST') THEN val
    ELSE LEFT(val, 2) || 'XX'
  END;

